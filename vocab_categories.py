def norm(s):
    return re.sub(r"\s+", " ", re.sub(r"[.!?,;:…]+$", "", s.strip().lower()))


def _kw(en):
    for cat, rx in KW:
        if rx.search(en):
            return cat
    return None


def _theme(ho, les, top):
    for h in ho:
        if h in HANDOUT:
            return HANDOUT[h]
    for t in top:
        for sub, cat in TOPIC:
            if sub in t:
                return cat
    for l in les:
        if l.endswith(".PB"):
            return "phrases"
        if l in LESSON:
            return LESSON[l]
    return None


