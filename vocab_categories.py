def categorize(hr, en, pos=(), ho=(), les=(), top=(), override=None):
    """Return a category id for one word or phrase."""
    k = norm(hr)
    override = OVERRIDE if override is None else override
    if k in override:
        return override[k]
    first_hr = hr.split(" / ")[0].replace("…", " ").strip()
    words = len(first_hr.split())
    first_en = en.split(" / ")[0].strip()
    punct = hr.rstrip().endswith(("?", "!", ".", "…"))
    sentence = words >= 3 or punct
    small_ho = any(h in ("questions", "kwords", "conj", "short", "prep") for h in ho)
    if small_ho and words <= 3 and not punct:
        return "small"
    if les and all(l.endswith(".PB") for l in les):   # Phrase Book: idioms and set phrases
        return "greet" if GREET.search(en) and words <= 3 else "phrases"
    if not punct and words <= 4 and re.match(r"^\(?to\s", first_en, re.I) and not re.match(r"^to (?:the|a|an|my|your)\b", first_en, re.I):
        return "verbs"
    if not punct and words <= 2 and re.match(r"^(?:i|you|he|she|it|we|they)\s+(?!am\b|is\b|are\b)[a-z']+(?:\s*\(.*\))?$", first_en, re.I) and "noun" not in pos:
        return "verbs"
    if sentence:
        if GREET.search(en) or INTRO.match(hr.strip()):
            return "greet"
        return _kw(en) or "phrases"
    if "adj" in pos:
        if _kw(en) == "countries":
            return "countries"
        return "adj"
    if words == 1 and SMALL_EN.fullmatch(re.sub(r"\s*\(.*?\)", "", first_en).strip().lower() or "-"):
        return "small"
    if GREET.search(en) and words <= 3:
        return "greet"
    return _kw(en) or _theme(ho, les, top) or "phrases"
